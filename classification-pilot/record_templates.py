"""Record one template per waveform class and write master/src/templates.h.

Templates are the reference waveforms the nRF cross-correlates incoming windows
against. Recording flow (you are the ground truth -- you set the FG):

    1. Flash the RAW-streaming firmware first (firmware/signal-path-intan/master,
       advertises as 'cclosed-sigpath'). This script consumes that raw stream.
    2. Run this script. For each class it prompts you to set the function
       generator to that waveform, then captures a few seconds and averages
       many aligned cycles into one clean, z-scored template.
    3. It writes master/src/templates.h. Then flash classification-pilot/master.

    python record_templates.py            # record from the live FG over BLE
    python record_templates.py --analytic # no hardware: write ideal math templates

Keep the SAME function-generator frequency here and at classify time -- a
fixed-length template only matches its own period (see waveform_classification_
backrgound.md).
"""

import asyncio
import sys
from pathlib import Path

import numpy as np
from bleak import BleakClient, BleakScanner

NAME = "cclosed-sigpath"                              # the RAW-stream firmware
CHR = "12345678-1234-5678-1234-56789abcdef1"
FS = 10000                                            # sample rate, must match firmware
F0 = 500                                              # function-generator fundamental, Hz
TEMPLATE_LEN = 40                                     # samples per template (2 cycles at 500 Hz)
RECORD_SECONDS = 3.0
CLASSES = ["sine", "square", "triangle"]
HEADER_PATH = Path(__file__).parent / "master" / "src" / "templates.h"


def zscore(a):
    a = np.asarray(a, float)
    return (a - a.mean()) / (a.std() + 1e-12)


def build_template(samples, m):
    """Average many rising-zero-crossing-aligned cycles into one clean template."""
    x = np.asarray(samples, float)
    x = x - x.mean()
    crossings = np.where((x[:-1] <= 0) & (x[1:] > 0))[0]
    segs = [x[c:c + m] for c in crossings if c + m <= len(x)]
    if len(segs) < 3:
        raise RuntimeError(
            f"only {len(segs)} cycles captured - record longer, check the FG is on, "
            "or lower F0")
    return zscore(np.mean(segs, axis=0))


def analytic_templates(m):
    t = np.arange(m)
    phase = 2 * np.pi * t / (FS / F0)
    s = np.sin(phase)
    return {
        "sine":     zscore(s),
        "square":   zscore(np.sign(s)),
        "triangle": zscore((2 / np.pi) * np.arcsin(s)),
    }


def write_header(templates):
    m = len(templates[CLASSES[0]])
    out = [
        "#pragma once",
        "/* Auto-generated by record_templates.py -- do not edit by hand. */",
        f"/* fs={FS} Hz, f0={F0} Hz, template={m} samples, z-scored (mean 0, unit variance). */",
        f"#define N_CLASSES {len(CLASSES)}",
        f"#define TEMPLATE_LEN {m}",
        "static const char * const CLASS_NAMES[N_CLASSES] = { "
        + ", ".join(f'"{c}"' for c in CLASSES) + " };",
        "static const float TEMPLATES[N_CLASSES][TEMPLATE_LEN] = {",
    ]
    for name in CLASSES:
        vals = ", ".join(f"{v:.6f}f" for v in templates[name])
        out.append(f"    {{ {vals} }},  /* {name} */")
    out.append("};")
    HEADER_PATH.write_text("\n".join(out) + "\n")
    print(f"wrote {HEADER_PATH}")


async def record_all():
    """Connect ONCE and record all classes over the same link.

    The raw-stream firmware stops advertising after its first connection and
    does not auto-resume on disconnect, so a connect-per-class approach only
    finds the device the first time. One persistent connection avoids that.
    """
    print(f"scanning for '{NAME}'...")
    dev = await BleakScanner.find_device_by_name(NAME, timeout=30)
    if dev is None:
        raise RuntimeError(f"'{NAME}' not found - is the raw-stream firmware flashed & advertising? "
                           "(if you connected once already, reset the board so it re-advertises)")

    buf = []
    collecting = False

    def on_notify(_, data: bytearray):
        if collecting:
            vals = np.frombuffer(data, dtype="<u2", offset=2)   # skip 2-byte seq
            buf.extend(vals.astype(float))

    templates = {}
    async with BleakClient(dev) as client:
        print(f"connected to {dev.address}")
        await client.start_notify(CHR, on_notify)
        loop = asyncio.get_event_loop()
        for name in CLASSES:
            # run the blocking prompt off the event loop so BLE keepalive keeps
            # flowing and the link doesn't drop while you change the FG setting
            await loop.run_in_executor(
                None, input,
                f"\nSet the function generator to a {name.upper()} wave "
                f"({F0} Hz, ~1 mV), then press Enter to record {RECORD_SECONDS:.0f}s...")
            buf.clear()
            collecting = True
            await asyncio.sleep(RECORD_SECONDS)
            collecting = False
            if not client.is_connected:
                raise RuntimeError("BLE link dropped mid-recording - reset the board and retry")
            templates[name] = build_template(buf, TEMPLATE_LEN)
            print(f"  {name}: averaged template from {len(buf)} samples")
        await client.stop_notify(CHR)

    write_header(templates)


def main():
    if "--analytic" in sys.argv:
        write_header(analytic_templates(TEMPLATE_LEN))
        print("(ideal analytic templates - replace with real recordings for best accuracy)")
        return
    asyncio.run(record_all())


if __name__ == "__main__":
    main()
