#!/usr/bin/env python3
"""
Generate ndspi/slave/src/nd_data.h — one REAL 8-channel spike snippet that the
slave streams to the master over SPI.

Picks the cleanest instance of unit 46 (shank 0) from dataset.npz — the one
closest to the unit's mean template — and emits it as Q8 fixed-point microvolts
(value = uV * 256, int16) so it survives an integer SPI link. A 16-bit sum
checksum lets the master confirm the snippet arrived intact.

Usage:
    python firmware/spi/ndspi/gen_nd_data.py
"""
import numpy as np
from pathlib import Path

UNIT = 46
SHANK = 0
OUT = Path(__file__).parent / "slave" / "src" / "nd_data.h"
DATASET = Path(__file__).parents[3] / "dataset" / "dataset.npz"


def main():
    d = np.load(DATASET)
    snip, lab, sh = d["snippets"], d["labels"], d["shank_ids"]
    su = snip[(sh == SHANK) & (lab == UNIT)]        # (n, 40, 8) real snippets

    mean_wf = su.mean(0)
    idx = int(np.argmin(((su - mean_wf) ** 2).sum((1, 2)))) # closest to template
    q = np.round(su[idx] * 256).astype(np.int16)    # Q8 fixed-point microvolts
    NL, NC = q.shape
    chk = int(np.sum(q.astype(np.int64)) & 0xFFFF)  # 16-bit sum checksum

    L = []
    L += ["/* Real neural data: one 8-channel spike snippet of unit 46 (shank 0),",
          " * peak channel index 3. Values are Q8 fixed-point microvolts (uV*256),",
          " * int16. Auto-generated by gen_nd_data.py from dataset.npz. */",
          "#ifndef ND_DATA_H", "#define ND_DATA_H", "#include <stdint.h>",
          f"#define ND_LEN  {NL}   /* samples per channel */",
          f"#define ND_CH   {NC}    /* channels (one shank) */",
          "#define ND_PEAK 3    /* peak channel index */",
          f"#define ND_CHECKSUM 0x{chk:04X}u  /* 16-bit sum of all words */",
          "/* Row-major: nd_snippet[sample][channel] */",
          "static const int16_t nd_snippet[ND_LEN][ND_CH] = {"]
    for r in range(NL):
        L.append("    { " + ", ".join(f"{v:6d}" for v in q[r]) + " },")
    L += ["};", "#endif /* ND_DATA_H */"]
    OUT.write_text("\n".join(L) + "\n")
    print(f"wrote {OUT}: {NL}x{NC}, checksum=0x{chk:04X}")


if __name__ == "__main__":
    main()
